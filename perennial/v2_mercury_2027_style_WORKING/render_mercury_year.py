"""Year-parameterized Mercury annual events + True Node / Chiron positions.
WORKING: numbers from Swiss Ephemeris / Moshier; independent ephemeris validation pending.
Consumes only year-specific event CSV generated by generate_year_data.py.
"""
from __future__ import annotations
import argparse, csv, json, math
from datetime import datetime, timedelta, timezone
from pathlib import Path
import swisseph as swe
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.font_manager import FontProperties

ROOT=Path(__file__).resolve().parent
SIGNS='牡羊座 牡牛座 双子座 蟹座 獅子座 乙女座 天秤座 蠍座 射手座 山羊座 水瓶座 魚座'.split()
JST=timezone(timedelta(hours=9))

def jd_utc(t):
 u=t.astimezone(timezone.utc)
 return swe.julday(u.year,u.month,u.day,u.hour+u.minute/60+u.second/3600+u.microsecond/3.6e9)

def pos_at(t, body):
 lon=swe.calc_ut(jd_utc(t),body,swe.FLG_MOSEPH|swe.FLG_SPEED)[0][0]%360
 return lon

def sign_degree(lon, retro_ingress=False):
 sign=SIGNS[int(lon//30)%12]
 minute=int(math.floor(((lon%30)*60)+1e-7))
 if retro_ingress:
  minute=1799
 return f'{sign} {minute//60:02d}°{minute%60:02d}′'

def event_label(row):
 if row['分類']=='留':return '順行再開' if row['種類']=='順行開始' else row['種類']
 return '逆行入座' if row['種類']=='逆行方向' else '順行入座'

def render(year:int, outdir:Path):
 data=ROOT/'data'/f'{year}_主要イベント_自動計算.csv'
 if not data.exists():
  raise FileNotFoundError(f'指定年の計算データが未生成: {data}; 先に generate_year_data.py --year を実行')
 swe.set_ephe_path(str(ROOT/'ephe'))
 with data.open(encoding='utf-8-sig',newline='') as f:
  rows=[r for r in csv.DictReader(f) if r['対象']=='水星']
 if not rows:raise RuntimeError('水星イベント0件: 計算異常の可能性')
 outdir.mkdir(parents=True,exist_ok=True)
 records=[]
 for r in rows:
  t=datetime.fromisoformat(r['計算日時_JST'])
  assert t.year==year and t.utcoffset()==timedelta(hours=9)
  lon=float(r['黄経_度'])%360
  retro=(r['分類']=='サイン移動' and r['種類']=='逆行方向')
  if r['分類']=='サイン移動':
   # At reverse boundary, the destination sign is the sign just before boundary.
   target=(int(round(lon/30))-1 if retro else int(round(lon/30)))%12
   mdeg=f'{SIGNS[target]} '+('29°59′' if retro else '00°00′')
  else:mdeg=sign_degree(lon)
  rounded=t+timedelta(seconds=30)
  date=rounded.strftime('%Y-%m-%d'); time=rounded.strftime('%H:%M')
  records.append({'年':year,'日時_JST':date+' '+time,'分類':event_label(r),
   '水星サイン度数':mdeg,'ドラゴンヘッド位置':sign_degree(pos_at(t,swe.TRUE_NODE)),
   'キロン位置':sign_degree(pos_at(t,swe.CHIRON)),
   '水星黄経_未丸め':f'{lon:.10f}','元イベントID':r['event_id']})
 assert all(x['日時_JST'].startswith(str(year)) for x in records)
 assert not any('30°00′' in x['水星サイン度数'] for x in records)
 csvpath=outdir/f'{year}_水星年間運行詳細_ヘッド_キロン_WORKING.csv'
 fields=list(records[0].keys())
 with csvpath.open('w',encoding='utf-8-sig',newline='') as f:
  w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(records)
 # Single A4 landscape diagram; use consistent typographic grid.
 jp=FontProperties(fname='/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc')
 fig=plt.figure(figsize=(11.69,8.27),dpi=160,facecolor='#f7f9fa')
 ax=fig.add_axes([0,0,1,1]);ax.set_xlim(0,1);ax.set_ylim(0,1);ax.axis('off')
 ax.add_patch(plt.Rectangle((0,.905),1,.095,color='#17334a'))
 ax.text(.048,.955,f'{year}  水星の年間運行詳細',fontproperties=jp,fontsize=22,color='white',va='center',weight='bold')
 ax.text(.95,.955,'HOSHITOURANAI',fontsize=11,color='#e7ce9c',ha='right',va='center')
 ax.text(.05,.877,'水星の入座・逆行開始・順行再開   ｜   同時刻のドラゴンヘッド・キロンの位置',fontproperties=jp,fontsize=11,color='#314c61',va='center')
 headers=['日時（JST）','水星イベント','水星の位置','ドラゴンヘッド','キロン']
 xs=[.055,.265,.43,.615,.805]
 ax.add_patch(plt.Rectangle((.045,.808),.91,.042,color='#dce6ea'))
 for x,h in zip(xs,headers):ax.text(x,.83,h,fontproperties=jp,fontsize=10.4,color='#17334a',va='center')
 n=len(records); start=.791; end=.17; step=(start-end)/max(n,1)
 for i,r in enumerate(records):
  y=start-i*step
  if i%2==0:ax.add_patch(plt.Rectangle((.045,y-step*.52),.91,step*.96,color='#ebf1f3',alpha=.75))
  vals=[r['日時_JST'],r['分類'],r['水星サイン度数'],r['ドラゴンヘッド位置'],r['キロン位置']]
  for x,v in zip(xs,vals):
   ax.text(x,y,v,fontproperties=jp,fontsize=9.6 if n<=24 else 8.6,va='center',color='#243e52')
 ax.plot([.045,.955],[.151,.151],color='#a3b5bf',lw=.9)
 notes=['※ 日時は日本時間・分単位四捨五入。度数はサイン内で切り捨て表示。',
        '※ 逆行入座は移動先サインの29°59′表記。表示のための規則であり計算上の黄経は改変しない。',
        '※ ドラゴンヘッド＝True Node。水星イベント時刻の位置をSwiss Ephemerisで計算。']
 for j,s in enumerate(notes):ax.text(.05,.129-j*.031,s,fontproperties=jp,fontsize=8.6,color='#516778')
 png=outdir/f'{year}_水星年間運行詳細_ヘッド_キロン_WORKING.png'
 fig.savefig(png,dpi=160,facecolor=fig.get_facecolor());plt.close(fig)
 manifest=outdir/f'{year}_水星年間運行詳細_検査_WORKING.json'
 manifest.write_text(json.dumps({'year':year,'count':n,'jst_all':True,'input':str(data.relative_to(ROOT)),
 'node':'True Node','chiron':'Swiss Ephemeris asteroid file', 'status':'WORKING: independent check not done',
 'output_csv':csv.name if False else csvpath.name,'output_png':png.name},ensure_ascii=False,indent=2),encoding='utf-8')
 print(f'{year} Mercury {n} events: {png}');return png,csvpath

if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--year',type=int,required=True);p.add_argument('--output',type=Path,default=ROOT/'output');a=p.parse_args();render(a.year,a.output)
